def _cookie_jar() -> CookieJar:
    jar = CookieJar()
    jar.set_cookie(
        Cookie(
            version=0,
            name="session",
            value="private-token",
            port=None,
            port_specified=False,
            domain=".example.com",
            domain_specified=True,
            domain_initial_dot=True,
            path="/",
            path_specified=True,
            secure=False,
            expires=None,
            discard=True,
            comment=None,
            comment_url=None,
            rest={},
            rfc2109=False,
        )
    )
    return jar


def test_browser_cookies_are_loaded_for_the_requested_domain(monkeypatch):
    captured: list[str] = []

    def load_chrome(*, domain_name: str) -> CookieJar:
        captured.append(domain_name)
        return _cookie_jar()

    fake_module = SimpleNamespace(chrome=load_chrome)
    monkeypatch.setitem(sys.modules, "browser_cookie3", fake_module)

    jar = load_cookies_from_browser("chrome", "https://www.example.com/watch")

    assert captured == ["www.example.com"]
    assert [cookie.name for cookie in jar] == ["session"]


def test_cookie_browser_is_available_for_extraction_and_download():
    url = "https://www.example.com/watch"

    assert ExtractRequest(url=url, cookies_from_browser="chrome").cookies_from_browser == "chrome"
    assert DownloadRequest(url=url, cookies_from_browser="edge").cookies_from_browser == "edge"


def test_browser_cookies_do_not_leak_to_other_domains(settings):
    seen: dict[str, str | None] = {}

    def handler(request: httpx.Request) -> httpx.Response:
        seen[request.url.host] = request.headers.get("cookie")
        return httpx.Response(200, content=b"ok")

    async def scenario() -> None:
        async with HttpClient(
            settings,
            cookie_jar=_cookie_jar(),
            transport=httpx.MockTransport(handler),
        ) as http:
            await http.get("https://www.example.com/video")
            await http.get("https://unrelated.test/video")

    run(scenario())

    assert seen["www.example.com"] == "session=private-token"
    assert seen["unrelated.test"] is None


def test_parse_netscape_and_json_cookies(tmp_path):
    from app.core.http.cookies import (
        get_cookie_file_stats,
        load_netscape_cookiejar,
        parse_cookies_text,
        save_cookie_jar,
    )

    netscape_text = (
        "# Netscape HTTP Cookie File\n"
        "# Generated by Get cookies.txt LOCALLY\n"
        ".youtube.com\tTRUE\t/\tTRUE\t1792747556\tVISITOR_INFO1_LIVE\tyt_token\n"
        "#HttpOnly_.pixabay.com\tTRUE\t/\tTRUE\t1792747556\t__cf_bm\tcf_token\n"
    )

    jar, domains = parse_cookies_text(netscape_text)
    cookies_list = list(jar)
    assert len(cookies_list) == 2
    assert "youtube.com" in domains
    assert "pixabay.com" in domains

    cookie_file = tmp_path / "cookies.txt"
    save_cookie_jar(jar, cookie_file)
    assert cookie_file.exists()

    loaded_jar = load_netscape_cookiejar(cookie_file)
    assert len(list(loaded_jar)) == 2

    stats = get_cookie_file_stats(cookie_file)
    assert stats["present"] is True
    assert stats["count"] == 2
    assert "pixabay.com" in stats["domains"]


def test_cookies_api_endpoints():
    from fastapi.testclient import TestClient
    from app.main import app

    with TestClient(app) as client:
        netscape_text = (
            "# Netscape HTTP Cookie File\n"
            ".pixabay.com\tTRUE\t/\tTRUE\t1792747556\t__cf_bm\ttest_token\n"
        )

        # 1. Upload via JSON content
        resp = client.post("/api/cookies/upload", json={"content": netscape_text})
        assert resp.status_code == 200
        data = resp.json()
        assert data["ok"] is True
        assert data["count"] == 1
        assert "pixabay.com" in data["domains"]

        # 2. Check status
        status_resp = client.get("/api/cookies")
        assert status_resp.status_code == 200
        status_data = status_resp.json()
        assert status_data["present"] is True
        assert status_data["count"] == 1

        # 3. Delete cookies
        del_resp = client.delete("/api/cookies")
        assert del_resp.status_code == 200

        # 4. Check status again
        status_after = client.get("/api/cookies")
        assert status_after.json()["present"] is False
